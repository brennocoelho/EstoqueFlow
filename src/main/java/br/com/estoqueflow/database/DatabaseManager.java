
package br.com.estoqueflow.database;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.sql.Statement;

public final class DatabaseManager {

    private static final Path DIRETORIO = Path.of(
            System.getProperty("user.home"),
            "EstoqueFlow",
            "data"
    );

    private static final String URL =
            "jdbc:h2:file:" +
                    DIRETORIO.resolve("estoque")
                            .toAbsolutePath()
                            .toString()
                            .replace('\\', '/');

    private DatabaseManager() {
    }

    public static Connection conectar() throws SQLException {
        try {
            Files.createDirectories(DIRETORIO);
        } catch (IOException e) {
            throw new SQLException(
                    "Erro ao criar diretório do banco.", e
            );
        }

        return DriverManager.getConnection(URL, "sa", "");
    }

    public static void inicializar() throws SQLException {
        try (
                Connection conexao = conectar();
                Statement stmt = conexao.createStatement()
        ) {
            stmt.executeUpdate("""
                CREATE TABLE IF NOT EXISTS produtos (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY
                        PRIMARY KEY,
                    codigo VARCHAR(30) NOT NULL UNIQUE,
                    nome VARCHAR(120) NOT NULL,
                    categoria VARCHAR(80) NOT NULL,
                    preco DECIMAL(15,2) NOT NULL
                        CHECK (preco >= 0),
                    quantidade INT NOT NULL DEFAULT 0
                        CHECK (quantidade >= 0),
                    estoque_minimo INT NOT NULL DEFAULT 0
                        CHECK (estoque_minimo >= 0),
                    ativo BOOLEAN NOT NULL DEFAULT TRUE
                )
                """);

            stmt.executeUpdate("""
                CREATE TABLE IF NOT EXISTS movimentacoes (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY
                        PRIMARY KEY,
                    produto_id BIGINT NOT NULL,
                    tipo VARCHAR(10) NOT NULL
                        CHECK (tipo IN ('ENTRADA', 'SAIDA')),
                    quantidade INT NOT NULL
                        CHECK (quantidade > 0),
                    data_hora TIMESTAMP NOT NULL
                        DEFAULT CURRENT_TIMESTAMP,
                    observacao VARCHAR(500),

                    CONSTRAINT fk_movimentacao_produto
                        FOREIGN KEY (produto_id)
                        REFERENCES produtos(id)
                )
                """);
        }
    }

    public static Path caminhoArquivo() {
        return DIRETORIO.resolve("estoque.mv.db");
    }
}
